	public void reset() { reset(Power, rational); }

	/**Adding a pair of Values to the Extrapolator.
	 * These Values are changed during Calculation, so better make copies beforehand.
	 * Returns convergence or maximum number of Pairs.
	 */
	public boolean addPoint(IIntRing x, IIntRing y) {
		//{Das Feld wird von hinten aufgefuellt und berechnet}
		if (Compare == null) Compare = ((IMetricIRing) y).mulAbsAccuracy();
		boolean maxPt = super.addPoint(x, y);	//This Method only returns true, when the max. number of points is reached
		if (intrvl == null) {intrvl = new IntervalOrd((IOrder) yDat[0], (IOrder) yDat[0]); return false;}
		else intrvl.addPoint (yDat[0]);		//Hilf contains the Difference to the old Value
		return  (converge = Compare.notLessThan(((IMetricIRing) Hilf).AbsVAt()))	//prevent early evaluation, calculate this first!
				|| maxPt; //{stets 2 Extrapolationsschritte}
	}

	/**Does a more thorough Evaluation of the Extrapolation Behavior
	 * to distinguish between Convergence, definite and indefinite Divergence.
	 */
	public IIntRing Evaluation() {
		IMetricIRing f_alt = (IMetricIRing) yDat[0];
		if (mDim < MaxGrad) return f_alt;       //{evtl. Divergenz}
		if (converge) return f_alt;
		if (intrvl.Position(f_alt) == 0) return null;	//unbestimmt divergent!
		if (f_alt.isMoreThan(alt))return (IIntRing) f_alt.   Infinity();	//  bestimmt divergent!
		else				return (IIntRing) f_alt.NegInfinity();	//for this you need MetricBody Methods!
	}

	/**Calculates the Limes of a Series.
	 * The Parameter Power determines the assumed Error Power Series.
	 * The Parameter rational determines,
	 * whether rational or polynomial Approximation is used.
	 * The Series will be generated by a ByRefLong, starting with 1.	 */
	public IIntRing Limes(IIntRing testObject, IFunction F, int Power, boolean rational) {
		reset(Power, rational);
		IIntRing Zaehler = (IIntRing) testObject.one();
		//  ByRefLong Zaehler = new ByRefLong (1);
		IIntRing PSum = (IIntRing) F.Map(Zaehler);
		IIntRing Position = (IIntRing) PSum.one();
		addPoint(Position, PSum);
		boolean Ende;
		do {
			Zaehler . dblAt(); //Zaehler.Value <<= 1;
			Position.halfAt();
			Ende = addPoint (Position, (IIntRing) F.Map(Zaehler));
		} while (! Ende);
		return Evaluation();
	}

	/**Calculates the Sum of a Series.
	 * The Parameter Power determines the assumed Error Power Series.
	 * The Parameter rational determines,
	 * whether rational or polynomial Approximation is used.
	 * The Series will be generated by a ByRefLong, starting with 1.	 */
	public IIntRing Reihe(IIntRing testObject, IFunction F, int Power, boolean rational) {
		reset(Power, rational);
		int Z1 = 1;
		IIntRing Zaehler = (IIntRing) testObject.one();
		//  ByRefLong Zaehler = new ByRefLong (1);
		IIntRing PSum = (IIntRing) F.Map(Zaehler); //{Partial-Summen ab 1}
		IIntRing Position = (IIntRing) PSum.one();
		addPoint(Position, PSum);
		boolean Ende;
		do {
			Z1 <<= 1;
			Position.halfAt();
			while (((ICountAble)Zaehler).getInt() < Z1)
				PSum.addAt (F.Map(Zaehler.inc()));   //{PartialSumme von 1..Z bleibt}
			Ende = addPoint(Position, PSum);
		} while (! Ende);
		return Evaluation(); }


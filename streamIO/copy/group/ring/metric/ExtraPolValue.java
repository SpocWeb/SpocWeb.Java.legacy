	public IIntRing lim (IFunction F, IIntRing x0, IIntRing h) {
		//{f (x0+h) = f (x0)+h*f' (x0)+h�*f'' (x0)+... }
		reset();
//		MetricIRing one = (MetricIRing) h.one();
//		IIntRing Help = (one.less(h))? (IIntRing) one.divAt(h) : h;
		boolean Ende;
		do {
//  		Compare.MaxAt (f_alt.absV());
			Ende = addPoint (Hilf, (IIntRing) F.Map(x0.add(h)));
			h.mulAt (h);Hilf.sqrAt();
		} while (! Ende);
		return Evaluation (); }

